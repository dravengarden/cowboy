//! Scoped supervision knowledge and participation. Native agents still own tasks.
pub mod patterns;
#[cfg(test)]
mod tests;

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

pub const SCOPE: &str = "superagent";
pub const PROMPT_PREFIX: &str = "cowboy-superagent:";
/// Trusted Controller context, never decoded from user queue JSON.
#[derive(Debug, Clone)]
pub struct DispatchContext {
    pub owner: String,
    pub coordinator: String,
    pub worker: String,
    pub revision: i64,
    pub evidence: String,
    pub follow_up: bool,
}

impl DispatchContext {
    pub fn target(&self) -> &str {
        if self.follow_up {
            &self.worker
        } else {
            &self.coordinator
        }
    }
    pub fn peer(&self) -> &str {
        if self.follow_up {
            &self.coordinator
        } else {
            &self.worker
        }
    }
}

#[derive(Debug, Clone, Copy, Default, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum Mode {
    #[default]
    Off,
    Observe,
    Coordinate,
}

#[derive(Debug, Clone, Default, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Settings {
    #[serde(default)]
    pub sources: Vec<patterns::Source>,
    #[serde(default)]
    pub projects: BTreeMap<String, Project>,
    /// Explicit enrollment; moving a folder never changes this binding.
    #[serde(default)]
    pub sessions: BTreeMap<String, Participation>,
}

#[derive(Debug, Clone, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Project {
    pub profile: String,
    /// Existing ordinary native session. It stays visible and keeps its account.
    pub coordinator: String,
    #[serde(default)]
    pub mode: Mode,
    /// Only strong models; the configured native session must match at dispatch.
    pub preset: Preset,
    #[serde(default = "default_limit")]
    pub max_followups: u8,
    #[serde(default)]
    pub learning: bool,
}

#[derive(Debug, Clone, Copy, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum Preset {
    AstraMax,
    FableMax,
}

pub const fn default_limit() -> u8 {
    2
}

#[derive(Debug, Clone, Deserialize, Serialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct Participation {
    pub project: String,
    /// None inherits the project; Some(Off) is an explicit exclusion.
    #[serde(default)]
    pub mode: Option<Mode>,
    /// The bounded task scope supplied at enrollment, never generated by a pattern.
    #[serde(default)]
    pub mandate: String,
}

impl Settings {
    pub fn patched(&self, changes: &serde_json::Value) -> Result<Self, &'static str> {
        Self::patch_value(&serde_json::to_value(self).unwrap(), changes)
    }

    /// Replace damaged library fields before decoding, so owners can repair an import.
    pub fn patch_value(
        current: &serde_json::Value,
        changes: &serde_json::Value,
    ) -> Result<Self, &'static str> {
        if !patch_shape(changes) {
            return Err("invalid_superagent_settings");
        }
        let mut next = current.clone();
        if !next.is_object() {
            return Err("invalid_superagent_settings");
        }
        for (key, value) in changes["configuration"].as_object().unwrap() {
            next[key] = value.clone();
        }
        let next: Self = serde_json::from_value(next).map_err(|_| "invalid_superagent_settings")?;
        next.validate()?;
        Ok(next)
    }

    pub fn validate(&self) -> Result<(), &'static str> {
        if self.sources.len() > 32 || self.projects.len() > 64 || self.sessions.len() > 512 {
            return Err("superagent_settings_limit");
        }
        let library = patterns::Library::compile(&self.sources)?;
        let mut coordinators = std::collections::BTreeSet::new();
        for (id, project) in &self.projects {
            if !valid_id(id)
                || !valid_id(&project.coordinator)
                || !(1..=5).contains(&project.max_followups)
                || !coordinators.insert(&project.coordinator)
                || self.sessions.contains_key(&project.coordinator)
            {
                return Err("invalid_superagent_project");
            }
            let catalog = library.resolve(&project.profile)?;
            if project.mode == Mode::Coordinate && !catalog.complete() {
                return Err("superagent_procedure_missing");
            }
        }
        for (id, session) in &self.sessions {
            if !valid_id(id)
                || !self.projects.contains_key(&session.project)
                || session.mandate.len() > 2000
            {
                return Err("invalid_superagent_participation");
            }
            if self
                .effective(id)
                .is_some_and(|(_, _, mode)| mode == Mode::Coordinate)
            {
                if session.mandate.trim().is_empty() {
                    return Err("superagent_mandate_required");
                }
                if !library
                    .resolve(&self.projects[&session.project].profile)?
                    .complete()
                {
                    return Err("superagent_procedure_missing");
                }
            }
        }
        Ok(())
    }

    pub fn effective(&self, session: &str) -> Option<(&Participation, &Project, Mode)> {
        let participation = self.sessions.get(session)?;
        let project = self.projects.get(&participation.project)?;
        Some((
            participation,
            project,
            participation.mode.unwrap_or(project.mode),
        ))
    }

    pub fn coordinator(&self, session: &str) -> Option<(&str, &Project)> {
        self.projects
            .iter()
            .find(|(_, p)| p.coordinator == session)
            .map(|(id, p)| (id.as_str(), p))
    }
}

pub fn valid_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 128
        && id
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"-_.".contains(&c))
}

pub fn patch_shape(changes: &serde_json::Value) -> bool {
    changes.as_object().is_some_and(|v| v.len() == 1)
        && changes["configuration"].as_object().is_some_and(|v| {
            !v.is_empty()
                && v.keys()
                    .all(|key| matches!(key.as_str(), "sources" | "projects" | "sessions"))
        })
}

/// Keep Markdown bodies out of MCP preference traffic, including write receipts.
pub fn settings_discovery(mut value: serde_json::Value) -> serde_json::Value {
    for key in ["preferences", "current"] {
        if value[key]["scope"] != SCOPE {
            continue;
        }
        let Some(config) = value[key]
            .pointer_mut("/values/configuration")
            .and_then(serde_json::Value::as_object_mut)
        else {
            continue;
        };
        let sources = config.remove("sources").unwrap_or_default();
        value[key]["source_catalog"] = serde_json::Value::Array(
            sources
                .as_array()
                .into_iter()
                .flatten()
                .map(|s| {
                    serde_json::json!({"profile":s["profile"],"revision":s["revision"],
                "digest":patterns::digest(&serde_json::to_vec(s).unwrap()),
                "file_count":s["files"].as_object().map(serde_json::Map::len)})
                })
                .collect(),
        );
    }
    value
}
