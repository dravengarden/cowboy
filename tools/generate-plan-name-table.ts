// Generates the Controller's dependency-free table of code points an
// account plan name may not contain: every Unicode category C character
// (control, format, surrogate, private use, unassigned) and the line and
// paragraph separators. It is derived from the exact rule the Antigravity
// proxy and the Web apply, `/[\p{C}\p{Zl}\p{Zp}]/u`, evaluated by the pinned
// Bun, so all three agree for the Unicode version recorded in the output.
//
// Run from the repository root in the dev shell after a Bun update that
// advances `process.versions.unicode`:
//   bun tools/generate-plan-name-table.ts
// `--check` fails when the committed table differs from the generated one.
import { readFileSync, writeFileSync } from "node:fs";

const OUTPUT = "components/server-accounts/src/server/provider_accounts/controls/plan/unprintable.rs";
const FORBIDDEN = /[\p{C}\p{Zl}\p{Zp}]/u;

function ranges(): [number, number][] {
  const found: [number, number][] = [];
  for (let code = 0; code <= 0x10ffff; code += 1) {
    if (!FORBIDDEN.test(String.fromCodePoint(code))) continue;
    const last = found.at(-1);
    if (last && last[1] === code - 1) last[1] = code;
    else found.push([code, code]);
  }
  return found;
}

function render(version: string, table: [number, number][]): string {
  const hex = (code: number) => `0x${code.toString(16).toUpperCase().padStart(4, "0")}`;
  const rows: string[] = [];
  for (let index = 0; index < table.length; index += 4) {
    rows.push(
      `    ${table
        .slice(index, index + 4)
        .map(([low, high]) => `(${hex(low)}, ${hex(high)}),`)
        .join(" ")}`,
    );
  }
  return [
    "// @generated by tools/generate-plan-name-table.ts; do not edit.",
    `//! Code points of \`[\\p{C}\\p{Zl}\\p{Zp}]\` in Unicode ${version}, as sorted,`,
    "//! disjoint, inclusive ranges.",
    "",
    "#[rustfmt::skip]",
    "pub(super) const RANGES: &[(u32, u32)] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

const version = process.versions.unicode;
if (typeof version !== "string")
  throw new Error("this runtime does not report its Unicode version");
const text = render(version, ranges());
if (process.argv.includes("--check")) {
  if (readFileSync(OUTPUT, "utf8") !== text) {
    console.error(`${OUTPUT} is stale; run bun tools/generate-plan-name-table.ts`);
    process.exit(1);
  }
} else {
  writeFileSync(OUTPUT, text);
}
