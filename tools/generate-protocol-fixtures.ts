// Turn the Rust-serialized wire fixtures in contracts/protocol/*.json into a
// TypeScript module whose literals must satisfy the hand-written types in
// web/src/protocol.ts. The web typecheck then fails when Rust adds, renames or
// changes the nullability of a field the TypeScript mirror does not declare
// (docs/structural-refactor-plan-2026-11.md, slice 0.4).
//
//   bun tools/generate-protocol-fixtures.ts           regenerate
//   bun tools/generate-protocol-fixtures.ts --check   fail when out of date
//
// The Rust side (src/protocol_contract.rs) owns the JSON: run its test with
// COWBOY_UPDATE_CONTRACTS=1 after changing a fixture.

import { readFile, writeFile } from "node:fs/promises";

/** Contract file -> exported constant and the protocol.ts type it satisfies. */
export const FAMILIES = [
  {
    file: "contracts/protocol/event.json",
    name: "eventFixtures",
    type: "Event",
  },
  {
    file: "contracts/protocol/outbound.json",
    name: "outboundFixtures",
    type: "Outbound",
  },
] as const;

export const OUTPUT = "web/src/protocol.fixtures.generated.ts";

interface Fixture {
  name: string;
  value: unknown;
}

export function render(
  families: { name: string; type: string; file: string; fixtures: Fixture[] }[],
): string {
  const types = [...new Set(families.map((family) => family.type))].sort();
  const lines = [
    "// Generated by tools/generate-protocol-fixtures.ts from contracts/protocol/*.json.",
    "// Do not edit. Each literal is Rust-serialized; `satisfies` makes the web",
    "// typecheck reject a field, tag or nullability the TypeScript types lack.",
    "",
    `import type { ${types.join(", ")} } from "./protocol";`,
    "",
  ];
  for (const family of families) {
    lines.push(`// ${family.file}`);
    lines.push(`export const ${family.name} = {`);
    for (const fixture of family.fixtures) {
      lines.push(`  ${JSON.stringify(fixture.name)}: ${JSON.stringify(fixture.value)},`);
    }
    lines.push(`} satisfies Record<string, ${family.type}>;`);
    lines.push("");
  }
  return lines.join("\n");
}

async function main(argv: string[]): Promise<number> {
  const families = [];
  for (const family of FAMILIES) {
    const fixtures = JSON.parse(await readFile(family.file, "utf8")) as Fixture[];
    families.push({ ...family, fixtures });
  }
  const output = render(families);
  if (argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== output) {
      console.error(`${OUTPUT} is out of date; run bun tools/generate-protocol-fixtures.ts`);
      return 1;
    }
    return 0;
  }
  await writeFile(OUTPUT, output);
  return 0;
}

if (import.meta.main) {
  process.exit(await main(process.argv.slice(2)));
}
